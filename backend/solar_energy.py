"""
ARC LUNA — LUNAR LANDING SITE NAVIGATOR
Module: solar_energy.py
Purpose: Solar array instantaneous electrical power generation and numerical integration
         of energy yield over mission durations.
Mathematical Formulation:
  P(t) = G(t) * A * eta * cos(theta(t)) * f_loss
  E = \\int_{t_0}^{t_1} P(t) dt
Where:
  P      = Electrical power generated (Watts)
  G      = Effective incident solar irradiance (W/m^2)
  A      = Total solar panel active collector area (m^2)
  eta    = Space-grade PV cell conversion efficiency (e.g. 0.30 for InGaP/GaAs/Ge triple-junction)
  theta  = Solar incidence angle between Sun vector and panel surface normal
  f_loss = Composite system loss derating factor (dust, wiring, MPPT, thermal derating)
"""

import math
from datetime import datetime, timezone, timedelta
from typing import Dict, Any, List, Optional, Tuple
from solar_illumination import (
    calculate_solar_illumination,
    get_sun_vector_cartesian,
    estimate_terrain_horizon_mask
)
from lunar_coordinates import (
    get_local_topocentric_basis,
    vector_to_azimuth_elevation
)


def calculate_panel_normal_vector(lat_deg: float, lon_deg: float,
                                  tilt_from_horizontal_deg: float = 90.0,
                                  azimuth_orientation_deg: float = 0.0) -> Tuple[float, float, float]:
    """
    Computes the panel surface normal unit vector in selenocentric Cartesian frame.
    
    Tilt conventions:
      - 0°: Flat on ground (facing local zenith)
      - 90°: Vertical panel (standard for lunar south pole to capture grazing horizontal sunlight)
    Azimuth conventions:
      - 0°: Facing North (toward equator)
      - 90°: Facing East
      - 180°: Facing South
      - 270°: Facing West
    """
    east, north, up = get_local_topocentric_basis(lat_deg, lon_deg)
    
    tilt_rad = math.radians(tilt_from_horizontal_deg)
    az_rad = math.radians(azimuth_orientation_deg)
    
    # In topocentric ENU:
    # tilt=0 (horizontal) => normal = (0, 0, 1) [Up]
    # tilt=90 (vertical facing az) => normal = (sin(az)*sin(tilt), cos(az)*sin(tilt), cos(tilt))
    e_comp = math.sin(az_rad) * math.sin(tilt_rad)
    n_comp = math.cos(az_rad) * math.sin(tilt_rad)
    u_comp = math.cos(tilt_rad)
    
    # Project to selenocentric Cartesian
    nx = e_comp * east[0] + n_comp * north[0] + u_comp * up[0]
    ny = e_comp * east[1] + n_comp * north[1] + u_comp * up[1]
    nz = e_comp * east[2] + n_comp * north[2] + u_comp * up[2]
    
    return nx, ny, nz


def calculate_instantaneous_power(
    lat_deg: float,
    lon_deg: float,
    elevation_m: float = 0.0,
    panel_area_m2: float = 6.0,
    efficiency: float = 0.30,
    tracking_mode: str = "VERTICAL_ROTATING",
    fixed_tilt_deg: float = 90.0,
    fixed_azimuth_deg: float = 0.0,
    dust_degradation: float = 0.05,
    mppt_efficiency: float = 0.95,
    dt: Optional[datetime] = None
) -> Dict[str, Any]:
    """
    Calculates instantaneous electrical power generated by a solar array.
    
    Tracking modes:
      1. 'VERTICAL_ROTATING': Rotates around vertical axis to face Sun azimuth (typical for Artemis landers).
      2. 'DUAL_AXIS_TRACKING': Directly tracks Sun azimuth and elevation (normal vector aligns with Sun).
      3. 'FIXED': Fixed tilt and azimuth orientation.
      4. 'HORIZONTAL': Flat horizontal panel on lander deck.
    """
    if dt is None:
        dt = datetime.now(timezone.utc)
        
    illum = calculate_solar_illumination(lat_deg, lon_deg, elevation_m, dt)
    sun_pos = illum["sun_position"]
    is_illuminated = illum["illumination"]["is_illuminated"]
    solar_flux_w_m2 = illum["illumination"]["solar_flux_w_m2"]
    
    if not is_illuminated or solar_flux_w_m2 <= 0.0:
        return {
            "power_watts": 0.0,
            "power_kw": 0.0,
            "illumination_status": "SHADOWED_OR_NIGHT",
            "cos_theta": 0.0,
            "effective_flux_w_m2": 0.0,
            "sun_elevation_deg": sun_pos["elevation_deg"],
            "sun_azimuth_deg": sun_pos["azimuth_deg"],
            "losses": {
                "dust_loss_pct": dust_degradation * 100.0,
                "mppt_loss_pct": (1.0 - mppt_efficiency) * 100.0,
                "shadow_loss": "100% (Terrain or Eclipse Shadow)"
            }
        }
        
    sun_el = sun_pos["elevation_deg"]
    sun_az = sun_pos["azimuth_deg"]
    
    # Compute cos(theta) according to tracking geometry
    if tracking_mode == "DUAL_AXIS_TRACKING":
        # Panel directly faces the Sun
        cos_theta = 1.0
        effective_tilt = 90.0 - sun_el
        effective_az = sun_az
    elif tracking_mode == "VERTICAL_ROTATING":
        # Vertical panel (90° tilt) that rotates azimuthally to face the Sun (azimuth error = 0)
        # Angle between vertical normal and Sun vector = 90° - sun_elevation
        # Therefore cos(theta) = cos(sun_elevation)
        cos_theta = max(0.0, math.cos(math.radians(sun_el)))
        effective_tilt = 90.0
        effective_az = sun_az
    elif tracking_mode == "HORIZONTAL":
        # Flat horizontal: cos(theta) = sin(sun_elevation)
        # Note: at South Pole, Sun elevation is small (0° to 1.5°), so horizontal panels receive very little power!
        cos_theta = max(0.0, math.sin(math.radians(sun_el)))
        effective_tilt = 0.0
        effective_az = 0.0
    else:  # FIXED
        # Fixed panel vector
        pn = calculate_panel_normal_vector(lat_deg, lon_deg, fixed_tilt_deg, fixed_azimuth_deg)
        sun_vec = get_sun_vector_cartesian(dt)
        dot = pn[0] * sun_vec[0] + pn[1] * sun_vec[1] + pn[2] * sun_vec[2]
        cos_theta = max(0.0, dot)
        effective_tilt = fixed_tilt_deg
        effective_az = fixed_azimuth_deg
        
    # Temperature derating: high efficiency PV cells have -0.3% / K temperature coefficient
    # In cold polar environment (T ~ 180 K), efficiency is actually enhanced above 298 K STC!
    t_cell_k = illum["thermal_state"]["temperature_kelvin"]
    temp_factor = 1.0 + (298.15 - t_cell_k) * 0.0025  # Gain at low temperatures
    temp_factor = max(0.85, min(1.20, temp_factor))
    
    composite_derate = (1.0 - dust_degradation) * mppt_efficiency * temp_factor
    
    power_w = solar_flux_w_m2 * panel_area_m2 * efficiency * cos_theta * composite_derate
    
    return {
        "timestamp_utc": dt.isoformat(),
        "power_watts": round(power_w, 2),
        "power_kw": round(power_w / 1000.0, 3),
        "illumination_status": "DIRECT_SUNLIGHT",
        "cos_theta": round(cos_theta, 4),
        "sun_elevation_deg": sun_el,
        "sun_azimuth_deg": sun_az,
        "panel_parameters": {
            "tracking_mode": tracking_mode,
            "effective_tilt_deg": round(effective_tilt, 1),
            "effective_azimuth_deg": round(effective_az, 1),
            "area_m2": panel_area_m2,
            "base_efficiency": efficiency,
            "dust_degradation_factor": dust_degradation,
            "mppt_efficiency": mppt_efficiency,
            "temperature_gain_factor": round(temp_factor, 3),
            "composite_loss_factor": round(composite_derate, 3)
        }
    }


def integrate_solar_energy(
    lat_deg: float,
    lon_deg: float,
    elevation_m: float = 0.0,
    start_dt: Optional[datetime] = None,
    duration_hours: float = 72.0,
    step_minutes: float = 30.0,
    panel_area_m2: float = 6.0,
    efficiency: float = 0.30,
    tracking_mode: str = "VERTICAL_ROTATING"
) -> Dict[str, Any]:
    """
    Numerically integrates electrical energy yield E = \\int P(t) dt over a mission time window
    using trapezoidal integration.
    """
    if start_dt is None:
        start_dt = datetime.now(timezone.utc)
    elif start_dt.tzinfo is None:
        start_dt = start_dt.replace(tzinfo=timezone.utc)
        
    num_steps = max(2, int((duration_hours * 60.0) / step_minutes))
    delta_step = timedelta(minutes=step_minutes)
    dt_seconds = step_minutes * 60.0
    
    time_series = []
    total_energy_joules = 0.0
    total_illuminated_seconds = 0.0
    peak_power_w = 0.0
    
    current_time = start_dt
    prev_power = None
    
    for i in range(num_steps + 1):
        p_res = calculate_instantaneous_power(
            lat_deg=lat_deg,
            lon_deg=lon_deg,
            elevation_m=elevation_m,
            panel_area_m2=panel_area_m2,
            efficiency=efficiency,
            tracking_mode=tracking_mode,
            dt=current_time
        )
        curr_power = p_res["power_watts"]
        if curr_power > peak_power_w:
            peak_power_w = curr_power
            
        if p_res["illumination_status"] == "DIRECT_SUNLIGHT":
            total_illuminated_seconds += dt_seconds
            
        if prev_power is not None:
            # Trapezoidal numerical integration: (P_prev + P_curr) / 2 * dt
            step_joules = ((prev_power + curr_power) / 2.0) * dt_seconds
            total_energy_joules += step_joules
            
        prev_power = curr_power
        
        # Keep time series points reasonable for plotting (~50 points)
        if i % max(1, num_steps // 40) == 0:
            time_series.append({
                "time_offset_hours": round((i * step_minutes) / 60.0, 2),
                "timestamp_utc": current_time.isoformat(),
                "power_watts": round(curr_power, 1),
                "sun_elevation_deg": p_res["sun_elevation_deg"],
                "is_illuminated": p_res["illumination_status"] == "DIRECT_SUNLIGHT"
            })
            
        current_time += delta_step
        
    total_energy_kwh = total_energy_joules / (3600.0 * 1000.0)
    avg_power_w = (total_energy_joules / (duration_hours * 3600.0))
    illum_fraction_pct = (total_illuminated_seconds / (duration_hours * 3600.0)) * 100.0
    
    return {
        "status": "COMPUTED",
        "inputs": {
            "latitude_deg": lat_deg,
            "longitude_deg": lon_deg,
            "elevation_m": elevation_m,
            "start_time_utc": start_dt.isoformat(),
            "duration_hours": duration_hours,
            "panel_area_m2": panel_area_m2,
            "efficiency": efficiency,
            "tracking_mode": tracking_mode
        },
        "results": {
            "total_energy_kwh": round(total_energy_kwh, 3),
            "total_energy_megajoules": round(total_energy_joules / 1e6, 2),
            "average_power_watts": round(avg_power_w, 2),
            "peak_power_watts": round(peak_power_w, 2),
            "sunlight_coverage_pct": round(min(100.0, illum_fraction_pct), 1),
            "shadow_duration_hours": round(duration_hours * (1.0 - illum_fraction_pct / 100.0), 2)
        },
        "time_series_samples": time_series,
        "assumptions": {
            "irradiance": "1361.0 W/m^2 solar constant corrected for Earth-Moon distance",
            "cell_type": "Multi-junction InGaP/InGaAs/Ge space-grade photovoltaic cells",
            "thermal_derating": "Empirical low-temperature efficiency boost included (+0.25%/K below 298K)",
            "integration_scheme": f"Trapezoidal numerical quadrature with step size {step_minutes} minutes"
        }
    }
